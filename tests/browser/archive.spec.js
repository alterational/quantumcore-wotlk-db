import {test,expect} from '@playwright/test';
import fs from 'node:fs';
const catalog=JSON.parse(fs.readFileSync('data/catalog.json','utf8'));
const world=catalog.databases.find(d=>d.name==='world');
const populated=world.tables.find(t=>t.rows>500 && t.status==='ok');
const meta=JSON.parse(fs.readFileSync(`data/world/${populated.name}/meta.json`,'utf8'));
const sample=JSON.parse(fs.readFileSync(`data/world/${populated.name}/${meta.chunks[0].file}`,'utf8'))[0];
test('home, catalog filter and back navigation with small initial payload',async({page})=>{
  const urls=[];const errors=[];
  page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>urls.push(r.url()));
  await page.goto('');
  await expect(page.getByRole('heading',{name:'База знаний игрового мира'})).toBeVisible();
  await expect(page.locator('.card')).toHaveCount(4);
  expect(urls.filter(u=>u.includes('/data/')).every(u=>u.endsWith('catalog.json'))).toBeTruthy();
  await page.getByRole('searchbox',{name:'Поиск таблиц'}).fill('quest_template');
  await page.getByRole('link',{name:'quest_template',exact:true}).click();
  await expect(page.getByRole('heading',{name:'quest_template',exact:true})).toBeVisible();
  await expect(page.getByRole('note')).toContainText('отсутствуют');
  await page.getByText('Структура таблицы').click();
  await expect(page.getByText('Исходный CREATE TABLE')).toBeVisible();
  await page.getByRole('link',{name:'Все базы',exact:true}).click();
  await expect(page.locator('.card')).toHaveCount(4);
  expect(errors).toEqual([]);
});
test('real rows, pagination, column search, reset, read-only network',async({page})=>{
  const methods=[];page.on('request',r=>methods.push(r.method()));
  await page.goto(`#world/${populated.name}`);
  await expect(page.locator('.data-table tbody tr')).toHaveCount(50);
  const first=await page.locator('.data-table tbody tr').first().textContent();
  await page.getByRole('button',{name:'Далее',exact:true}).click();
  await expect(page.locator('.data-table tbody tr').first().locator('td').first()).toHaveText('51');
  await page.getByRole('button',{name:'Назад',exact:true}).click();
  await expect(page.locator('.data-table tbody tr').first()).toHaveText(first);
  await page.getByRole('searchbox').fill(sample[0]);
  await page.getByRole('combobox',{name:'Поле поиска'}).selectOption('0');
  await page.getByLabel('Точное совпадение').check();
  await page.getByRole('button',{name:'Найти',exact:true}).click();
  await expect(page.getByRole('status')).toContainText(/Поиск завершён|Показаны первые/,{timeout:45000});
  const cells=await page.locator('.data-table tbody tr td:nth-child(2)').allTextContents();
  expect(cells.length).toBeGreaterThan(0);expect(cells.every(v=>v===sample[0])).toBeTruthy();
  await page.getByRole('button',{name:'Сбросить'}).click();
  await expect(page.locator('.data-table tbody tr')).toHaveCount(50);
  expect(methods.every(m=>m==='GET')).toBeTruthy();
});
test('empty, invalid route, fetch error recovery',async({page})=>{
  const empty=catalog.databases.flatMap(d=>d.tables.map(t=>({...t,db:d.name}))).find(t=>t.status==='ok'&&!t.rows);
  await page.goto(`#${empty.db}/${empty.name}`);
  await expect(page.getByText('Таблица существует и проверена', {exact:false})).toBeVisible();
  await page.goto('#world/not-a-table');await expect(page.getByRole('heading',{name:'Раздел не найден'})).toBeVisible();
  await page.route('**/meta.json',r=>r.fulfill({status:503,body:'Unavailable'}));
  await page.goto(`#world/${populated.name}`);await expect(page.getByRole('alert')).toContainText('503');
  await page.unroute('**/meta.json');await page.reload();await expect(page.locator('.data-table tbody tr')).toHaveCount(50);
});
test('mobile, XSS-safe cells, full text dialog',async({page})=>{
  await page.setViewportSize({width:375,height:812});
  await page.goto('');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  const value='<img src=x onerror="window.xss=true">'+ 'Тест '.repeat(40);
  await page.route(`**/data/world/${populated.name}/00000.json`,async r=>{
    const rows=JSON.parse(fs.readFileSync(`data/world/${populated.name}/00000.json`,'utf8'));
    rows[0][0]=value;await r.fulfill({json:rows});
  });
  await page.goto(`#world/${populated.name}`);
  await page.locator('.cell-open').first().click();await expect(page.getByRole('dialog')).toContainText(value);
  expect(await page.evaluate(()=>window.xss)).toBeUndefined();
  await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).toHaveCount(0);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
});
