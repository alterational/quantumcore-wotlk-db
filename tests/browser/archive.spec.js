test('bounded search, last page, missing chunk retry',async({page})=>{
  await page.goto('#world/waypoint_data');
  await expect(page.locator('.data-table tbody tr')).toHaveCount(50);
  await page.getByRole('searchbox').fill('0');
  await page.getByRole('button',{name:'Найти',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Показаны первые 200');
  await expect(page.locator('.data-table tbody tr')).toHaveCount(50);
  await page.getByRole('button',{name:'Сбросить'}).click();
  await page.getByRole('button',{name:'Последняя страница'}).click();
  await expect(page.locator('.data-table tbody tr')).toHaveCount(47);
  const m=JSON.parse(fs.readFileSync('data/world/waypoint_data/meta.json'));
  const last=m.chunks.at(-1).file;
  await page.route(`**/waypoint_data/${last}`,r=>r.fulfill({status:404}));
  await page.reload();await expect(page.locator('.data-table tbody tr')).toHaveCount(50);
  await page.getByRole('button',{name:'Последняя страница'}).click();
  await expect(page.getByRole('status')).toContainText('Ошибка загрузки');
  await page.unroute(`**/waypoint_data/${last}`);
  await page.getByRole('button',{name:'Сбросить'}).click();
  await expect(page.getByRole('status')).toContainText('Показаны исходные значения');
});
